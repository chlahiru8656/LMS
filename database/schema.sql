-- ============================================================
-- Laboratory Management System - BML
-- Database Schema
-- Department of Civil Engineering, University of Sri Jayewardenepura
-- ============================================================

CREATE DATABASE IF NOT EXISTS lms_bml;
USE lms_bml;

-- ============================================================
-- 1. USERS
-- ============================================================
CREATE TABLE users (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role ENUM('master_admin', 'course_coordinator', 'instructor', 'lab_incharge', 'lab_to', 'lab_assistant', 'student') NOT NULL DEFAULT 'student',
    student_staff_id VARCHAR(50) UNIQUE,
    phone VARCHAR(20),
    status ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

