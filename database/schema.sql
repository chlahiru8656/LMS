-- ============================================================
-- 3. ACADEMIC HIERARCHY
-- ============================================================
CREATE TABLE batches (
    id INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    year INT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE semesters (
    id INT AUTO_INCREMENT PRIMARY KEY,
    batch_id INT NOT NULL,
    semester_number INT NOT NULL,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
);

CREATE TABLE courses (
    id INT AUTO_INCREMENT PRIMARY KEY,
    semester_id INT NOT NULL,
    code VARCHAR(20) NOT NULL,
    name VARCHAR(255) NOT NULL,
    coordinator_id INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (semester_id) REFERENCES semesters(id) ON DELETE CASCADE,
    FOREIGN KEY (coordinator_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE course_enrollments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    course_id INT NOT NULL,
    student_id INT NOT NULL,
    enrolled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    UNIQUE KEY unique_enrollment (course_id, student_id)
);

-- ============================================================
-- 4. PRACTICALS
-- ============================================================
CREATE TABLE practicals (
    id INT AUTO_INCREMENT PRIMARY KEY,
    course_id INT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    lab_sheet_url VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);

-- ============================================================
-- 5. EQUIPMENT
-- ============================================================
CREATE TABLE equipment (
    id INT AUTO_INCREMENT PRIMARY KEY,
    lab_id INT NOT NULL DEFAULT 1,
    name VARCHAR(255) NOT NULL,
    model VARCHAR(255),
    serial_number VARCHAR(100),
    manufacturer VARCHAR(255),
    location_in_lab VARCHAR(255),
    status ENUM('available', 'in_use', 'maintenance', 'out_of_service') DEFAULT 'available',
    next_calibration_due DATE,
    image_url VARCHAR(500),
    description TEXT,
    created_by INT,
    approved_by INT,
    approval_status ENUM('approved', 'pending') DEFAULT 'approved',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (lab_id) REFERENCES labs(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ============================================================
-- 6. CONSUMABLES
-- ============================================================
CREATE TABLE consumables (
    id INT AUTO_INCREMENT PRIMARY KEY,
    lab_id INT NOT NULL DEFAULT 1,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    unit VARCHAR(50) NOT NULL,
    current_stock DECIMAL(10,2) DEFAULT 0,
    min_threshold DECIMAL(10,2) DEFAULT 0,
    created_by INT,
    approved_by INT,
    approval_status ENUM('approved', 'pending') DEFAULT 'approved',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (lab_id) REFERENCES labs(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ============================================================
-- 7. PRACTICAL REQUIREMENTS (Equipment & Materials)
-- ============================================================
CREATE TABLE practical_equipment (
    id INT AUTO_INCREMENT PRIMARY KEY,
    practical_id INT NOT NULL,
    equipment_id INT NOT NULL,
    quantity_needed INT DEFAULT 1,
    FOREIGN KEY (practical_id) REFERENCES practicals(id) ON DELETE CASCADE,
    FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE
);

CREATE TABLE practical_materials (
    id INT AUTO_INCREMENT PRIMARY KEY,
    practical_id INT NOT NULL,
    consumable_id INT NOT NULL,
    quantity_needed DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (practical_id) REFERENCES practicals(id) ON DELETE CASCADE,
    FOREIGN KEY (consumable_id) REFERENCES consumables(id) ON DELETE CASCADE
);

-- ============================================================
-- 8. BOOKING REQUESTS
-- ============================================================
CREATE TABLE booking_requests (
    id INT AUTO_INCREMENT PRIMARY KEY,
    practical_id INT NOT NULL,
    requested_by INT NOT NULL,
    instructor_id INT NOT NULL,
    lab_id INT NOT NULL DEFAULT 1,
    booking_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    group_name VARCHAR(50),
    status ENUM('pending', 'to_reviewed', 'approved', 'rejected', 'cancelled') DEFAULT 'pending',
    incharge_remarks TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (practical_id) REFERENCES practicals(id) ON DELETE CASCADE,
    FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (instructor_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (lab_id) REFERENCES labs(id) ON DELETE CASCADE
);

CREATE TABLE booking_students (
    id INT AUTO_INCREMENT PRIMARY KEY,
    booking_request_id INT NOT NULL,
    student_id INT NOT NULL,
    FOREIGN KEY (booking_request_id) REFERENCES booking_requests(id) ON DELETE CASCADE,
    FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE booking_comments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    booking_request_id INT NOT NULL,
    commented_by INT NOT NULL,
    comment TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (booking_request_id) REFERENCES booking_requests(id) ON DELETE CASCADE,
    FOREIGN KEY (commented_by) REFERENCES users(id) ON DELETE CASCADE
);

-- ============================================================
-- 9. MAINTENANCE LOGS
-- ============================================================
CREATE TABLE maintenance_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    equipment_id INT NOT NULL,
    maintenance_date DATE NOT NULL,
    maintenance_type ENUM('preventive', 'corrective', 'routine') NOT NULL,
    description TEXT,
    performed_by VARCHAR(255),
    cost DECIMAL(10,2),
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ============================================================
-- 10. CALIBRATIONS
-- ============================================================
CREATE TABLE calibrations (
    id INT AUTO_INCREMENT PRIMARY KEY,
    equipment_id INT NOT NULL,
    calibration_date DATE NOT NULL,
    next_due_date DATE NOT NULL,
    performed_by VARCHAR(255),
    certificate_number VARCHAR(100),
    remarks TEXT,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ============================================================
-- 11. USAGE LOGS (Consumables)
-- ============================================================
CREATE TABLE usage_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    consumable_id INT NOT NULL,
    used_by INT NOT NULL,
    quantity_used DECIMAL(10,2) NOT NULL,
    usage_date DATE NOT NULL,
    purpose VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (consumable_id) REFERENCES consumables(id) ON DELETE CASCADE,
    FOREIGN KEY (used_by) REFERENCES users(id) ON DELETE CASCADE
);

-- ============================================================
-- 12. REPLENISHMENTS (Consumables)
-- ============================================================
CREATE TABLE replenishments (
    id INT AUTO_INCREMENT PRIMARY KEY,
    consumable_id INT NOT NULL,
    quantity_added DECIMAL(10,2) NOT NULL,
    replenishment_date DATE NOT NULL,
    supplier VARCHAR(255),
    cost DECIMAL(10,2),
    remarks TEXT,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (consumable_id) REFERENCES consumables(id) ON DELETE CASCADE,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

-- ============================================================
-- 13. CLEANING SCHEDULES
-- ============================================================
CREATE TABLE cleaning_schedules (
    id INT AUTO_INCREMENT PRIMARY KEY,
    lab_id INT NOT NULL DEFAULT 1,
    equipment_id INT,
    task_name VARCHAR(255) NOT NULL,
    description TEXT,
    frequency ENUM('daily', 'weekly', 'monthly', 'custom') NOT NULL,
    assigned_to VARCHAR(255),
    scheduled_time TIME,
    day_of_week TINYINT,
    day_of_month TINYINT,
    is_active BOOLEAN DEFAULT TRUE,
    created_by INT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (lab_id) REFERENCES labs(id) ON DELETE CASCADE,
    FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE SET NULL,
    FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE cleaning_logs (
    id INT AUTO_INCREMENT PRIMARY KEY,
    schedule_id INT NOT NULL,
    scheduled_date DATE NOT NULL,
    completed_date DATE,
    completed_time TIME,
    status ENUM('pending', 'completed', 'missed') DEFAULT 'pending',
    completed_by VARCHAR(255),
    remarks TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (schedule_id) REFERENCES cleaning_schedules(id) ON DELETE CASCADE
);
